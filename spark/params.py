def parse_synthetic_strength(val, num_synthetic=None):
    """Parse a ``synthetic_strength`` value that may be scalar OR per-site.

    Accepts:
      - numeric scalar (int/float)               -> returned as float
      - list / tuple / ndarray of numerics       -> returned as 1-D float ndarray
      - string from a CSV cell, either a plain
        scalar ("1.0") or a list form
        ("[1, 10, 1, 0.5, 10]" or "1,10,1,0.5,10",
        semicolons also accepted as separators)  -> parsed accordingly
      - None / NaN / empty string                -> defaults to 1.0

    If ``num_synthetic`` is provided and the parsed value is an array, its
    length must equal ``num_synthetic`` (when num_synthetic > 0). A scalar
    is always valid.

    Scalars preserve the legacy behaviour (all synthetic sites get the same
    strength). Arrays set a per-site multiplier; element ``i`` corresponds
    to the i-th synthetic site in the order they were generated by
    ``generate_clustered_sites``.
    """
    # Missing / NaN / None -> default scalar
    if val is None:
        return 1.0
    if isinstance(val, float) and np.isnan(val):
        return 1.0

    # Already a numeric scalar (covers np.int*/np.float* via isinstance)
    if isinstance(val, (bool,)):
        # avoid silently accepting booleans
        return float(val)
    if isinstance(val, (int, np.integer)):
        return float(val)
    if isinstance(val, (float, np.floating)):
        return float(val)

    # Already a sequence
    if isinstance(val, (list, tuple, np.ndarray)):
        arr = np.asarray(val, dtype=float).ravel()
        if arr.size == 1:
            return float(arr[0])
        if num_synthetic is not None and num_synthetic > 0 and arr.size != num_synthetic:
            raise ValueError(
                "synthetic_strength has length %d but num_synthetic_sites=%d; "
                "pass a scalar or an array whose length matches the number "
                "of synthetic sites." % (arr.size, num_synthetic)
            )
        return arr

    # String from a CSV cell
    if isinstance(val, str):
        s = val.strip()
        if not s:
            return 1.0
        # Plain scalar string ("1.0", "10", "1e-3")
        try:
            return float(s)
        except ValueError:
            pass
        # List form: strip brackets / parens, allow ',' or ';' as separators
        s_clean = s.strip("[](){}").replace(";", ",")
        parts = [p.strip() for p in s_clean.split(",") if p.strip()]
        if not parts:
            return 1.0
        try:
            arr = np.asarray([float(p) for p in parts], dtype=float)
        except ValueError as e:
            raise ValueError(
                "Could not parse synthetic_strength %r as a scalar or a "
                "list of floats." % val
            ) from e
        if arr.size == 1:
            return float(arr[0])
        if num_synthetic is not None and num_synthetic > 0 and arr.size != num_synthetic:
            raise ValueError(
                "synthetic_strength has length %d but num_synthetic_sites=%d; "
                "pass a scalar or an array whose length matches the number "
                "of synthetic sites." % (arr.size, num_synthetic)
            )
        return arr

    # Unknown type -> best-effort float cast
    return float(val)


def _given(row, key):
    v = row.get(key, None)
    return v is not None and not (isinstance(v, float) and np.isnan(v))


def binding_rate(row):
    """Binding rate k_on (1/s) of a row and where it came from.

    k_on column if present; otherwise the older per-step probability
    k_on_prob converted with k_on = -ln(1 - k_on_prob) / sim_dt (the same
    per-step probability without cooperativity; k_on_prob = 1 -> inf);
    otherwise inf (binding on contact). Returns (k_on, source).
    """
    if _given(row, 'k_on'):
        return float(row['k_on']), 'k_on'
    if _given(row, 'k_on_prob'):
        prob = float(row['k_on_prob'])
        if not 0.0 <= prob <= 1.0:
            raise ValueError("k_on_prob must be within 0..1 (got %r)" % prob)
        dt = float(row.get('sim_dt', DEFAULTS['sim_dt']))
        k_on = np.inf if prob >= 1.0 else -np.log1p(-prob) / dt
        return k_on, 'k_on_prob'
    return np.inf, 'default'


def extract_row_params(row):
    """Extract simulation parameters from a batch CSV row."""
    p = {}
    p['cluster_dist'] = {
        int(row.get('cluster_size_%d' % i, i + 1)): float(row.get('cluster_pct_%d' % i, 20.0))
        for i in range(5)
    }
    p['strength_multipliers'] = [
        row.get('strength_mult_%d' % i, STRENGTH_MULTIPLIERS_DEFAULT[i]) for i in range(5)
    ]
    p['strength_percentages'] = [row.get('strength_pct_%d' % i, 20.0) for i in range(5)]
    p['cluster_correlated'] = row.get('cluster_correlated_strength', False)
    p['cluster_radius_nm'] = float(row.get('cluster_radius_nm', 150.0))
    p['strength_range'] = (min(p['strength_multipliers']), max(p['strength_multipliers']))
    p['bs_hurst'] = row.get('bs_hurst', 0.25)
    p['exposure_time_s'] = row.get('exposure_time_ms', 50.0) / 1000.0
    p['num_synthetic'] = int(row.get('num_synthetic_sites', 0))
    # synthetic_strength may be a scalar OR a per-site array (string like
    # "[1, 10, 1, 0.5, 10]" in the CSV, or already a list/array if a caller
    # built the row dict in Python). Length must match p['num_synthetic']
    # when an array is given.
    p['synthetic_strength'] = parse_synthetic_strength(
        row.get('synthetic_strength', 1.0), num_synthetic=p['num_synthetic'])
    p['synthetic_radius'] = row.get('synthetic_cluster_radius_nm', 150.0)
    p['upscale_factor'] = int(row.get('upscale_factor', 12))
    p['lateral_fwhm'] = float(row.get('lateral_fwhm_nm', 200.0))
    p['axial_fwhm'] = float(row.get('axial_fwhm_nm', 600.0))
    p['enable_coop'] = bool(row.get('enable_cooperativity', False))
    p['coop_strength'] = float(row.get('coop_strength', 1.0))
    p['coop_hill'] = float(row.get('coop_hill', 1.0))
    p['coop_off_strength'] = float(row.get('coop_off_strength', 0.0))
    p['coop_off_hill'] = float(row.get('coop_off_hill', 1.0))
    p['k_on'], p['k_on_source'] = binding_rate(row)
    p['two_state_mode'] = bool(row.get('two_state_mode', True))
    p['num_slices'] = int(row.get('num_slices', DEFAULTS['num_slices']))
    # Display noise: only used for auto-normalized convolved images.
    p['display_noise_enabled'] = bool(row.get('display_noise_enabled', False))
    p['display_noise_floor_pct'] = float(row.get('display_noise_floor_pct', 2.0))
    p['display_noise_std_pct'] = float(row.get('display_noise_std_pct', 1.0))
    p['au_ref_concentration_nM'] = float(row.get('au_ref_concentration_nM', 500.0))
    p['au_ref_signal'] = float(row.get('au_ref_signal', 80.0))
    p['au_background'] = float(row.get('au_background', 100.0))
    p['au_noise_std'] = float(row.get('au_noise_std', 5.0))
    rl = str(row.get('label', ''))
    p['row_label'] = "".join(c for c in rl if c.isalnum() or c in (' ', '_', '-')).strip()
    return p
